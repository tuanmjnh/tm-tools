import { spawn } from 'child_process'
import fs from 'fs'
import path from 'path'
import type { IBrowserAdapter, DetectionResult } from '../../../domain/browser/BrowserAdapter'
import type { BrowserProcess, LaunchOptions } from '../../../domain/browser/BrowserProcess'
import type { BrowserCapabilities, BrowserEngine } from '../../../../../shared/contracts/browser.ipc'
import { getExecutableVersion, killProcessTree, getConfiguredPath } from './browserUtils'

export class CamoufoxAdapter implements IBrowserAdapter {
  public readonly id = 'camoufox-adapter'
  public readonly name = 'Camoufox Anti-detect Browser'
  public readonly engine: BrowserEngine = 'camoufox'

  public async detect(): Promise<DetectionResult[]> {
    const results: DetectionResult[] = []
    const candidates: string[] = []

    const configuredPath = getConfiguredPath('CAMOUFOX_PATH')
    if (configuredPath) {
      candidates.push(configuredPath)
    }

    if (process.platform === 'win32') {
      const localAppData = process.env.LOCALAPPDATA || ''
      const appData = process.env.APPDATA || ''
      candidates.push(
        path.join(localAppData, 'camoufox', 'camoufox.exe'),
        path.join(localAppData, 'Programs', 'camoufox', 'camoufox.exe'),
        path.join(appData, 'camoufox', 'camoufox.exe'),
        path.join(process.cwd(), 'resources', 'bin', 'camoufox', 'camoufox.exe')
      )
    } else {
      candidates.push(
        '/usr/local/bin/camoufox',
        '/usr/bin/camoufox',
        path.join(process.env.HOME || '', '.local', 'bin', 'camoufox')
      )
    }

    for (const exePath of candidates) {
      if (fs.existsSync(exePath)) {
        try {
          const version = await this.getVersion(exePath)
          results.push({
            installed: true,
            name: 'Camoufox Browser',
            path: exePath,
            version,
            engine: 'camoufox'
          })
          break
        } catch {
          // ignore
        }
      }
    }

    return results
  }

  public async getVersion(executablePath: string): Promise<string> {
    return getExecutableVersion(executablePath)
  }

  private generateUserJs(userDataDir: string, _options: LaunchOptions): void {
    const userJsPath = path.join(userDataDir, 'user.js')
    const lines: string[] = [
      '// Generated by TM Tools Camoufox Adapter',
      'user_pref("toolkit.telemetry.enabled", false);',
      'user_pref("toolkit.telemetry.unified", false);',
      'user_pref("experiments.activeExperiment", false);',
      'user_pref("experiments.supported", false);',
      'user_pref("network.cookie.cookieBehavior", 0);'
    ]

    // Timezone / Locale if configured
    lines.push('user_pref("intl.accept_languages", "vi-VN,vi,en-US,en");')

    try {
      fs.writeFileSync(userJsPath, lines.join('\n') + '\n', 'utf8')
    } catch {
      // ignore write error
    }
  }

  public async launch(options: LaunchOptions): Promise<BrowserProcess> {
    if (!fs.existsSync(options.executablePath)) {
      throw new Error(`Camoufox executable not found: ${options.executablePath}`)
    }

    if (!fs.existsSync(options.userDataDir)) {
      fs.mkdirSync(options.userDataDir, { recursive: true })
    }

    // Set custom user.js preferences
    this.generateUserJs(options.userDataDir, options)

    const finalArgs: string[] = [
      '-profile',
      options.userDataDir,
      '-no-remote',
      '-new-instance'
    ]

    if (options.viewport) {
      finalArgs.push('-width', String(options.viewport.width), '-height', String(options.viewport.height))
    }

    if (options.headless) {
      finalArgs.push('-headless')
    }

    if (options.args && options.args.length > 0) {
      finalArgs.push(...options.args)
    }

    const child = spawn(options.executablePath, finalArgs, {
      detached: false,
      stdio: ['ignore', 'pipe', 'pipe']
    })

    if (!child.pid) {
      throw new Error('Failed to spawn Camoufox process (PID is undefined)')
    }

    return {
      pid: child.pid,
      profileId: options.profileId,
      browserId: options.browserId,
      engine: 'camoufox',
      startedAt: new Date(),
      process: child,
      cdpPort: options.cdpPort,
      userDataDir: options.userDataDir
    }
  }

  public async close(pid: number): Promise<void> {
    await killProcessTree(pid, true)
  }

  public supports(): BrowserCapabilities {
    return {
      cdp: true,
      extensions: true,
      customArgs: true,
      incognito: true,
      headless: true
    }
  }
}
